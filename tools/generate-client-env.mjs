// Bakes the client-visible environment variables into a generated module.
//
// Browser bundles cannot read .env at runtime the way the API does, so the
// values have to be substituted at build time. This script runs before the
// client builds and writes the variables into a gitignored module that
// libs/client/env validates and exposes as clientEnv.
//
// Which variables those are is not repeated here: the list is read straight off
// clientEnvSchema, so adding a key to that schema is all it takes. Everything
// it names ships to browsers, so only publishable values belong in it.

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

const LIB_DIR = join(import.meta.dirname, '..', 'libs', 'client', 'env', 'src', 'lib');
const SCHEMA_PATH = join(LIB_DIR, 'client-env-schema.ts');
const OUTPUT_PATH = join(LIB_DIR, 'generated-env.ts');

// Imported as TypeScript directly, via Node's type stripping.
const { clientEnvSchema } = await import(pathToFileURL(SCHEMA_PATH).href);
const clientEnvVars = Object.keys(clientEnvSchema.shape);

try {
  process.loadEnvFile();
} catch {
  // no .env file; rely on the process environment
}

// Undefined means the variable was never set; an empty value is a real value,
// as for a base URL that is deliberately same-origin. The schema decides
// whether it is acceptable, not this script.
const missing = clientEnvVars.filter(
  (name) => process.env[name] === undefined,
);
if (missing.length > 0) {
  throw new Error(
    `Invalid or missing environment variables: ${missing.join(', ')}. ` +
      'Copy .env.example to .env and fill them from `supabase status`.',
  );
}

const entries = clientEnvVars
  .map((name) => `  ${name}: ${JSON.stringify(process.env[name])},`)
  .join('\n');

writeFileSync(
  OUTPUT_PATH,
  [
    '// Generated by tools/generate-client-env.mjs. Do not edit, do not commit.',
    '',
    'export const generatedEnv = {',
    entries,
    '};',
    '',
  ].join('\n'),
);
